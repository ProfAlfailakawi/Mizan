/*
 * نطاقُ المسابقة في المسارات التي تأخذ `competitionId` من جسم الطلب.
 *
 * هويةٌ مقيّدةٌ بمسابقة (مطالبة `competition_id`) لا تعمل في مسابقةٍ أخرى. كانت مساراتُ الختم
 * والنشر وتصحيح الدرجة وتغيير الرواية وتغيير السياسة تأخذ المعرّف من الجسم ولا تقارنه بالمطالبة؛
 * والمقارنةُ الوحيدة كانت في سجلّ التدقيق، وهو يُكتب **بعد** الأثر — وفي الإنتاج (السجلّ الدائم)
 * يُبتلع رفضُه بلا صوت. فمحكّمٌ رئيسٌ لمسابقة «أ» يختم أو ينشر في سجلّ مسابقة «ب».
 *
 * القاعدةُ نفسها التي تطبّقها `IntegrityAuthority.scoped` وسجلُّ التدقيق: هويةٌ بلا مسابقة
 * (نطاقُ المؤسسة) لا تُقيَّد هنا؛ والمؤسسةُ تُفحص في مواضعها كما كانت.
 */
export const competitionScopeMismatch = (actor: { competitionId?: string }, competitionId: string): boolean =>
  !!(actor.competitionId && competitionId && actor.competitionId !== competitionId);
