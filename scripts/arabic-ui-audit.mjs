import fs from 'fs';
import path from 'path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const failures=[];const checks=[];
const ok=(name,cond,detail='')=>{checks.push({name,cond,detail});if(!cond)failures.push(`${name}${detail?`: ${detail}`:''}`)};
const i18n=read('src/lib/i18n.ts');const arBlock=i18n.slice(i18n.indexOf('ar: {'),i18n.indexOf("  en: {"));
ok('Arabic dictionary does not expose MIZAN Latin brand',!arBlock.includes('MIZAN'));
ok('Arabic dictionary does not expose FairDraw',!arBlock.includes('FairDraw'));
ok('Arabic dictionary does not expose Digital Twin',!arBlock.includes('Digital Twin'));
ok('Arabic dictionary does not expose Dual Approval',!arBlock.includes('Dual Approval'));
const sci=read('src/components/admin/ScientificGovernance.tsx');
ok('Qiraat screen resolves Arabic imam labels',sci.includes('qiraahLabel(x,ar)'));
ok('Qiraat screen resolves Arabic rawi labels',sci.includes('rawiLabel(x,ar)'));
ok('Reference audio resolves Arabic reading labels',sci.includes('readingDisplay(x.qiraah,x.rawi,ar)'));
const mushaf=read('src/components/judge/OfficialMushafSurface.tsx');
ok('Judge Mushaf surface includes focus lens',mushaf.includes('<FocusLens'));
ok('Judge Mushaf surface localizes qiraah/rawi',mushaf.includes('qiraahLabel(reading,ar)')&&mushaf.includes('rawiLabel(reading,ar)'));
const ops=read('src/components/operations/CommandCenter.tsx');
ok('Operations uses zero-knowledge custody corridor',ops.includes('fetchCustodyCorridor')&&ops.includes('النص غير متاح للتشغيل'));
const main=read('src/main.tsx');
ok('Arabic dynamic safety guard mounted globally',main.includes('<ArabicInterfaceGuard/>'));
const auth=read('src/components/auth/AuthPortal.tsx');
ok('Authentication has Arabic-first labels',auth.includes("ar?'البريد الإلكتروني'")||auth.includes('البريد الإلكتروني'));
const trust=read('src/components/public/TrustVerification.tsx');
ok('Public verifier is language-aware',trust.includes("const ar=language==='ar'")&&trust.includes('تم التحقق من النتيجة'));
const onboarding=read('src/components/public/OnboardingExperience.tsx');
ok('Onboarding has three Arabic steps',onboarding.includes('أهلًا بك في ميزان')&&onboarding.includes('السؤال يبقى سرًا حتى اللحظة الصحيحة')&&onboarding.includes('كل ما يحتاجه يوم المسابقة'));
const logo=read('src/components/design-system/MizanLogo.tsx');
ok('Arabic brand wordmark is ميزان',logo.includes("ar?'ميزان':'MIZAN'"));
const html=read('index.html');
ok('Document defaults to Arabic RTL',html.includes('<html lang="ar" dir="rtl">'));
ok('Arabic metadata title',html.includes('<title>ميزان —'));
console.log(`Arabic UI audit: ${checks.filter(x=>x.cond).length}/${checks.length} checks passed.`);
if(failures.length){for(const f of failures)console.error(`FAIL: ${f}`);process.exit(1)}
