/*
 * تمييزُ ضجيج البيئة من عطبِ المنتج في سجلّ المتصفّح.
 *
 * فحوصُ الجودة تقود المنتجَ المبنيَّ في متصفّحٍ حقيقيّ وتعدّ كلَّ خطأ سجلٍّ عطبًا. وبعضُ
 * الأخطاء ليس عطبًا: خادمُ المعاينة يخدم ملفّاتٍ ساكنة ولا واجهةَ خادمٍ فيه، فكلُّ نداءٍ
 * إلى `/api/` يرجع 404 بحكم التصميم لا بحكم العطب.
 *
 * ولهذا كان الاستثناءُ يُكتب تعبيرًا على **نصّ** الخطأ، وفيه `404` مجرّدة. وتلك علّةٌ
 * قاتلة، وسببُها أن النصَّ لا يحمل الجواب أصلًا: Playwright يعطي للأربعةِ نصًّا واحدًا
 * حرفًا بحرف —
 *
 *     "Failed to load resource: the server responded with a status of 404 (Not Found)"
 *
 * — سواءٌ أكان المفقودُ `/api/public/competitions` أم `/assets/index-*.js` أم
 * `/fonts/KFGQPC.woff2`. والعنوانُ لا يظهر إلا في `location().url`. فمطابقةُ النصّ وحدَه
 * لا تستطيع التمييز، فابتلعت كلَّ 404 — ومنها **حزمةُ المنتج نفسها وخطُّ المصحف**. فكان
 * يمكن أن يمرّ الفحصُ أخضرَ والمنتجُ لا يحمّل أصولَه، وهو بعينه ما وُجد الفحصُ ليمسكه.
 *
 * فصار الحكمُ بالنصّ **والعنوان** معًا، لا بأحدهما:
 *
 *   · النصُّ يحمل **الحالة** — «404» أم «500» أم «401» — ولا يحمل هُويّةَ المورد.
 *   · والعنوانُ يحمل **الهُويّة** — `/api/` أم `/assets/` — ولا يحمل الحالة.
 *
 * وواحدٌ منهما وحدَه نصفُ حكم. فالنصُّ وحدَه ابتلع عطبَ المنتج كما مرّ؛ والعنوانُ وحدَه
 * يبتلع 500 و401 على `/api/` — وذلك أخطر، لأن `scripts/qa-public-registration.sh`
 * يشغّل الفحصَ نفسَه على **خادمٍ حقيقيّ** (`node dist/server.cjs`) بعد أن يتثبّت أن
 * `/api/public` يُخدَم فعلًا. فهناك `/api/` حيٌّ يُرزق، وخطؤه عطبٌ لا غياب.
 *
 * وقاعدتُه:
 *
 *   · ما غاب عن بيئة الفحص **بحكم التصميم** — بحالته وهُويّته معًا — يُستثنى، ويُسمّى
 *     سببُه ويُطبع، فلا يُكتم.
 *   · وما سواه يُبلَّغ، ولو كان على `/api/`، ولو كان 404.
 *   · وإن جُهل العنوان فلا استثناء: المجهولُ لا يُعذَر، والشكُّ يُقرأ عطبًا لا براءة.
 */

/** أخطاءُ طبقةِ الشبكة: تعذّر الوصولُ إلى مضيفٍ أصلًا، لا جوابُ تطبيق. */
const NETWORK_UNREACHABLE = /ERR_(CONNECTION|TUNNEL|NAME_NOT_RESOLVED|INTERNET)|Could not reach|Failed to load resource: net::/;

/** «غير موجود» كما يكتبها المتصفّح — وهي الحالةُ التي يحملها النصّ. */
const NOT_FOUND = /responded with a status of 404\b/;

/**
 * ما يغيب عن بيئة الفحص بحكم التصميم — قائمةٌ مغلقةٌ تُسمّى بأعيانها.
 *
 * وكلُّ قاعدةٍ تشترط الحالةَ والهُويّةَ معًا. ولا يُضاف إليها مسارٌ يخدمه البناءُ نفسُه
 * (`/assets/`، `/fonts/`، `/brand/`…): غيابُ واحدٍ من تلك عطبٌ في المنتج لا ضجيجٌ
 * في البيئة.
 */
const EXPECTED_ABSENT = [
  {
    matches: ({ text, url }) => NOT_FOUND.test(text) && /^[^?#]*\/api\//.test(url),
    ar: 'خادمُ المعاينة يخدم ملفّاتٍ ساكنة ولا واجهةَ `/api/` فيه — غيابٌ مقصود',
  },
];

/**
 * أيُبلَّغ هذا الخطأ أم يُستثنى؟
 *
 * @param {{ text: string, url?: string }} error نصُّ الخطأ وعنوانُ المورد إن عُرف.
 * @returns {{ suppressed: boolean, ar?: string }} و`ar` سببُ الاستثناء، يُطبع ولا يُكتم.
 */
export function classifyConsoleError({ text, url }) {
  if (NETWORK_UNREACHABLE.test(text)) {
    return { suppressed: true, ar: 'خدمةٌ خارجية غير متاحة في بيئة الفحص' };
  }
  if (!url) return { suppressed: false };
  for (const rule of EXPECTED_ABSENT) {
    if (rule.matches({ text, url })) return { suppressed: true, ar: rule.ar };
  }
  return { suppressed: false };
}
