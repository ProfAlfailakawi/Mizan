#!/usr/bin/env node
/*
 * تهيئة سلطة النزاهة: توليد مفتاح التوقيع، وطباعة ما يلزم لتشغيلها.
 *
 * المفتاح الخاص يُولَّد هنا ولا يُكتب في المستودع أبدًا. الخيار الافتراضي أن يُطبع لتضعه في
 * خزنة أسرار؛ و`--write-env` يكتبه في `.env.local` المستبعد من git للتطوير المحلي وحده.
 *
 * ولماذا سكربت أصلًا بدل سطر في دليل؟ لأن مفتاح التوقيع يُولَّد مرة واحدة ويُخزَّن في مكانين
 * (الخزنة، والخدمة)، ونسخُه يدويًا بين الأمرين هو حيث تضيع المفاتيح أو تُسرَّب.
 *
 * الاستعمال:
 *   node scripts/setup-integrity-authority.mjs              طباعة المفتاح والأوامر
 *   node scripts/setup-integrity-authority.mjs --write-env  كتابته في .env.local للتطوير
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const args = new Set(process.argv.slice(2));
const writeEnv = args.has('--write-env');

const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
const pem = privateKey.export({ format: 'pem', type: 'pkcs8' }).toString();
const spki = publicKey.export({ format: 'der', type: 'spki' }).toString('base64url');
const keyId = `ed25519:${crypto.createHash('sha256').update(spki).digest('hex').slice(0, 16)}`;

/* PEM متعدّد الأسطر لا يمرّ في ملف بيئة بسطر واحد؛ يُرمَّز فاصل السطر كما يتوقّعه الخادم. */
const singleLine = pem.replace(/\n/g, '\\n');

const say = (s = '') => process.stdout.write(`${s}\n`);

say('');
say('MIZAN — integrity authority setup');
say('=================================');
say('');
say(`Key id (public, safe to share): ${keyId}`);
say(`Public key (SPKI, base64url):   ${spki}`);
say('');

if (writeEnv) {
  const file = path.join(process.cwd(), '.env.local');
  const dir = path.join(process.cwd(), '.mizan-data', 'integrity-authority');
  const block = [
    '',
    '# Generated by scripts/setup-integrity-authority.mjs — never commit this file.',
    `MIZAN_TRUST_SIGNING_PRIVATE_KEY_PEM=${singleLine}`,
    `MIZAN_TRUST_KEY_ID=${keyId}`,
    `MIZAN_INTEGRITY_AUTHORITY_DIR=${dir}`,
    '',
  ].join('\n');
  fs.appendFileSync(file, block, { mode: 0o600 });
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  say(`Wrote local development values to ${file} (git-ignored) and created ${dir}.`);
  say('This is for local development only. Production keys belong in a secret manager.');
  say('');
} else {
  say('Private key — put this in your secret manager, not in the repository:');
  say('');
  say(pem.trim());
  say('');
  say('Google Cloud (project mizan-f2ce3, region me-central1):');
  say('');
  say('  # 1. Store the signing key.');
  say('  printf %s "$(cat the-key.pem)" | gcloud secrets create MIZAN_TRUST_SIGNING_PRIVATE_KEY_PEM --data-file=-');
  say('');
  say('  # 2. Give the Cloud Run service account read access.');
  say('  gcloud secrets add-iam-policy-binding MIZAN_TRUST_SIGNING_PRIVATE_KEY_PEM \\');
  say('    --member="serviceAccount:$(gcloud run services describe mizan --region me-central1 --format=\'value(spec.template.spec.serviceAccountName)\')" \\');
  say('    --role=roles/secretmanager.secretAccessor');
  say('');
  say('  # 3. A durable volume for the authority state, then point the service at it.');
  say('  #    Cloud Run container filesystems are per-instance and erased on restart: an');
  say('  #    unrevealed draw seed would be lost and two instances would disagree about who');
  say('  #    approved what. The server refuses to enable the authority on such a path.');
  say('  gcloud storage buckets create gs://mizan-integrity-authority --location=me-central1');
  say('  gcloud run services update mizan --region me-central1 \\');
  say('    --add-volume=name=authority,type=cloud-storage,bucket=mizan-integrity-authority \\');
  say('    --add-volume-mount=volume=authority,mount-path=/mnt/authority \\');
  say('    --update-env-vars=MIZAN_INTEGRITY_AUTHORITY_DIR=/mnt/authority,MIZAN_INTEGRITY_AUTHORITY_DURABLE=true,MIZAN_TRUST_KEY_ID=' + keyId + ' \\');
  say('    --update-secrets=MIZAN_TRUST_SIGNING_PRIVATE_KEY_PEM=MIZAN_TRUST_SIGNING_PRIVATE_KEY_PEM:latest');
  say('');
  say('Then confirm on the running service:');
  say('  curl -s https://<service-url>/api/health | grep -o \'"integrityAuthorityStatus":"[^"]*"\'');
  say('  # expected: "integrityAuthorityStatus":"ENABLED"   and "trustSigningConfigured":true');
  say('');
}

say('Keep the key id with your records: a seal names the key that signed it, and rotating the');
say('key without keeping the old public key makes older seals unverifiable.');
say('');
