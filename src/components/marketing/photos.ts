/*
 * صور البشر في الموقع التسويقي.
 *
 * الشاشات وحدها لا تبيع مسابقة؛ الوجوه هي التي تُشعر الزائر أن هذا يحدث في قاعةٍ
 * حقيقية. لكن صورة شخصٍ يُعرف وجهه على موقعٍ تجاري تحتاج إذنه هو، لا رخصة المصوّر
 * وحدها — فالمصدر الصحيح صور مسابقات الجهة نفسها، بإذن أهلها.
 *
 * حتى تصل تلك الصور، تبقى هذه القائمة فارغة وتُخفى أقسام الصور كلها: موقعٌ بلا صور
 * أفضل من موقعٍ بمربّعاتٍ فارغة أو بوعدٍ لم يُوفَ.
 *
 * لإضافتها: ضع الملفات في public/marketing/photos/ ثم أدرجها هنا. الأقسام تظهر وحدها.
 *   - العرض المقترح: 2000×1250 للشريط العريض، و1400×1750 للقائمة الرأسية.
 *   - كل صورة تحتاج `alt` يصف ما فيها لمن لا يراها.
 */
export interface MarketingPhoto {
  src: string;
  alt: string;
  /** سطرٌ واحد يظهر فوق الصورة. اتركه فارغًا لصورةٍ بلا نص. */
  caption?: string;
}

