/*
 * تسويةُ الرسم القرآنيّ للمقابلة — وهي أخطرُ ما في كشف الخطأ.
 *
 * فمن سوّى قليلًا خطّأ قارئًا مصيبًا؛ ومن سوّى كثيرًا أعمى عن خطأٍ وقع. والفرقُ بينهما
 * حرفٌ واحد.
 *
 * وتُبنى على طبقتين، لأنّ الخطأين ليسا سواءً:
 *
 *  ١) **الهيكل** (`quranSkeleton`) — الحروفُ وحدها بلا حركة. به تُعرف **الكلمة**:
 *     أقالها أم أسقطها أم أبدلها بغيرها. وهو الحكمُ الأوثق.
 *
 *  ٢) **المنطوق** (`quranVoweled`) — الحروفُ وحركاتُها، بلا علامات الوقف ولا رموز
 *     التجويد. به تُعرف **الحركة**: أضمّ موضعَ فتح؟ وهو حكمٌ أدقُّ وأضعفُ ثقةً،
 *     ومراجعاتٌ علميّةٌ منشورةٌ تقول إنّ الأنظمة القائمة تُخطئ فيه كثيرًا — فلا يُقال
 *     بثقةِ الأوّل.
 *
 * وحدٌّ لا يُتجاوز: **التسويةُ لا تُقارِن روايةً برواية**. كلُّ قارئٍ يُقابَل بنصّ
 * روايته هو. وإنّما يوحَّد الرسمُ لأنّ ما يُسمع من محرّكٍ صوتيٍّ يُكتب بهجاءٍ آخر —
 * لا ليُقاس ورشٌ بمسطرة حفص.
 */

/* علاماتٌ لا تُنطق: وقفٌ، وسجدةٌ، وأرقامُ آي، ورموزُ تجويدٍ صغيرة، وتطويل. */
const SILENT_MARKS = /[ـۖ-۝۞ۣۢۥۦۨ۩۪-ࣰۭ-ࣿ]/g;

/* حركاتٌ ومدٌّ: تُحذف في الهيكل وتبقى في المنطوق. */
const VOWEL_MARKS = /[ً-ْٖٓ-ٰٟ۟۠ۡۤۧ]/g;

/* صورُ الألف تُوحَّد في الهيكل وحدَه — والمدُّ والهمزُ حركةٌ لا حرفٌ مستقلّ هنا. */
const ALEF_FORMS = /[آأإٱٲٳٵ]/g;

/*
 * وصورتان لحركةٍ واحدة — تُوحَّدان، ولا يُوحَّد سواهما.
 *
 * فالسكونُ في الرسم العثمانيّ يُكتب رأسَ خاءٍ صغيرةً (U+06E1)، وفي الكتابة المعتادة
 * سكونًا (U+0652). **وهما منطوقٌ واحدٌ بصورتين**، لا فرقَ بينهما يُسمع.
 *
 * وقِيس أثرُ تركهما مفترقين: **٤٠٫٣٪** من كلمات حفصٍ تحمل U+06E1 (٣١٢٥٤ من ٧٧٦٢٩)،
 * وصفرٌ في ورش — بل حزمةُ ورشٍ نفسُها تكتب السكونَ U+0652 في ٣٧٥٥٣ موضعًا، وحزمةُ
 * حفصٍ تكتبه U+06E1 في ٣٧١٤٨. فلو قُوبل قارئُ حفصٍ بمحرّكٍ يكتب السكونَ المعتاد،
 * لخُطِّئ في **٤٠٪ من تلاوةٍ صحيحة** — وذلك عيبُ ترميزٍ لا عيبُ حفظ.
 *
 * ولا يُزاد على هذا شيء. فما بقي من رموز الرسم (إشاراتُ السكوت U+06DF و U+06E0،
 * ورموزُ المدّ الصغيرة) ليست صورتين لشيءٍ واحد، وتوحيدُها تسويةٌ بالظنّ تُعمي عن خطأٍ
 * وقع. وحارسُها غيرُ هذا: **بوّابةُ الحركة لا تُفتح لمحرّكٍ إلا بخطأِ حركةٍ مقيسٍ على
 * نصّ روايته**، فمحرّكٌ يكتب بهجاءٍ آخر يسقط في قياسه ويبقى بابُه مغلقًا.
 */
const VOWEL_SPELLINGS: readonly [RegExp, string][] = [
  [/\u06E1/g, '\u0652'],
];

/** ما يُنطق: الحروفُ وحركاتُها، بلا علامةِ وقفٍ ولا رمزِ تجويد. */
export function quranVoweled(text: string): string {
  let out = String(text || '').normalize('NFC').replace(SILENT_MARKS, '');
  for (const [from, to] of VOWEL_SPELLINGS) out = out.replace(from, to);
  /*
   * ويُعاد التطبيعُ **بعد** التوحيد لا قبله.
   *
   * فترتيبُ العلامات المتراكبة يُرتَّب بالتطبيع، وإبدالُ رمزٍ برمزٍ قد يغيّر رتبتَه.
   * وقِيس: ٢٣ كلمةً في حفصٍ فيها همزةٌ وسكونٌ معًا (نحو «يَسۡتَـٔۡذِنُكَ») بقيت مختلفةً
   * بعد التوحيد وحدَه — لأنّ أحدَ الطرفين طُبِّع قبل الإبدال والآخرَ بعده. فصارت
   * الدالّةُ تُطبّع آخرًا، فتستوي مهما جاء الترتيب.
   */
  return out.normalize('NFC').replace(/\s+/g, ' ').trim();
}

/**
 * هيكلُ الكلمة: حروفُها وحدها.
 *
 * وتُوحَّد صورُ الألف، والألفُ المقصورةُ بالياء، لأنّ محرّكًا صوتيًّا يكتبها كيفما
 * تعلّم. ولا تُوحَّد التاءُ المربوطةُ بالهاء: بينهما فرقٌ يُسمع.
 */
export function quranSkeleton(text: string): string {
  return quranVoweled(text)
    .replace(VOWEL_MARKS, '')
    .replace(ALEF_FORMS, 'ا')
    /*
     * والمدُّ بعد الهمزة يُرسم في المصحف همزةً على السطر بعدها ألف («ءَامَنُوا۟»، «ٱلْقُرْءَانَ»،
     * «ءَالَآءِ»)، ويُكتب في الهجاء المعتاد ألفَ مدّ («آمنوا»، «القرآن»، «آلاء») — وهي تُوحَّد
     * ألفًا في السطر الذي قبل هذا. وهما منطوقٌ واحد.
     *
     * قِيس في متصفّحٍ حقيقيّ: سمع المحرّكُ «آلاء» صحيحةً، فعُدّت «ءالاء» على الوجه «سُمع غيرُها»،
     * فخُطِّئ القارئُ في كلّ لازمةٍ من سورة الرحمن. وفي حفصٍ ١٠٧٥ كلمةً من هذا الرسم (١٫٣٪)
     * في ٩٤٢ آية (١٥٪): «ءامنوا» ٢٦٣ مرّة، و«ءايات» و«ءاية» ٩٩، و«القرءان» ٤٣، و«ءالاء» ٣٤.
     */
    .replace(/ءا/g, 'ا')
    /*
     * والياءُ المرسومةُ في مصاحف ورشٍ ياءٌ بَرِّيّة (U+06D2)، وفي مصاحف حفصٍ ياءٌ
     * معتادة. قِيس: ٢٩٩٦ موضعًا في ورشٍ وصفرٌ في حفص — كما أنّ ألفَ الوصل (U+0671)
     * ١٣٤٨٣ موضعًا في حفصٍ وصفرٌ في ورش. وهما رسمان لمنطوقٍ واحد؛ ولولا توحيدُهما
     * لقيل «كلمةٌ غيرُ كلمة» في آلاف المواضع الصحيحة.
     */
    .replace(/[ىے]/g, 'ي')
    .replace(/[ٕٔ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/*
 * الألفُ الخنجريّة (U+0670) مدٌّ يُكتب ألفًا في الهجاء الحديث حينًا ويُترك حينًا:
 * «ٱلۡعَٰلَمِينَ» تُكتب «العالمين»، و«ٱلرَّحۡمَٰنِ» تُكتب «الرحمن». فلا قاعدةَ تُطّرد.
 *
 * فيُقبل الاتّفاقُ إذا لم يفترق الرسمان إلا بألف. وثمنُه معلوم: كلمتان لا تختلفان
 * إلا بألفٍ (عالم/علم) تُعدّان واحدة على مستوى الكلمة. وذلك أهونُ من تخطئة قارئٍ
 * مصيبٍ في كلّ موضعِ مدٍّ — ومن اختلف في الحركة يُدركه كشفُ الحركة حين يُؤذن به.
 */
const withoutAlef = (skeleton: string) => skeleton.replace(/\u0627/g, '');

/** أهي الكلمةُ نفسُها حرفًا بحرف — بصرف النظر عن الحركة ورسمِ المدّ؟ */
export function sameWord(a: string, b: string): boolean {
  const sa = quranSkeleton(a), sb = quranSkeleton(b);
  if (!sa.length || !sb.length) return false;
  if (sa === sb) return true;
  const stripped = withoutAlef(sa);
  return stripped.length > 0 && stripped === withoutAlef(sb);
}

/*
 * كم تشبه الكلمةُ الكلمة؟ — من صفرٍ إلى واحد، على الهيكل: ١ − مسافةُ التحرير ÷ الأطول.
 *
 * لا يُحكم به على صوابٍ ولا خطأ. إنّما يفرّق بين كلمةٍ **أخطأ المحرّكُ سماعَها** وكلمةٍ **من غير
 * هذا الموضع**: فالمحرّكُ حين يُخطئ يُقارب («آلاكما» لـ«ءالاء»، «بكما» لـ«ربكما»، «منهم» لـ«منهما»)،
 * وكلامٌ من آيةٍ أخرى لا يشبه ما يقابله («الا» لـ«مرج»). والأولى قراءةٌ متّصلة، والثانية قفزة.
 */
export function wordLikeness(a: string, b: string): number {
  const sa = quranSkeleton(a), sb = quranSkeleton(b);
  if (!sa.length || !sb.length) return 0;
  const row = Array.from({ length: sb.length + 1 }, (_, j) => j);
  for (let i = 1; i <= sa.length; i += 1) {
    let diag = row[0]; row[0] = i;
    for (let j = 1; j <= sb.length; j += 1) {
      const up = row[j];
      row[j] = Math.min(row[j] + 1, row[j - 1] + 1, diag + (sa[i - 1] === sb[j - 1] ? 0 : 1));
      diag = up;
    }
  }
  return 1 - row[sb.length] / Math.max(sa.length, sb.length);
}

/** أهي بحركتها أيضًا؟ يُسأل بعد أن تثبت الكلمة، لا قبله. */
export const sameVowels = (a: string, b: string) => quranVoweled(a) === quranVoweled(b);
