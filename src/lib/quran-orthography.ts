/*
 * تسويةُ الرسم القرآنيّ للمقابلة — وهي أخطرُ ما في كشف الخطأ.
 *
 * فمن سوّى قليلًا خطّأ قارئًا مصيبًا؛ ومن سوّى كثيرًا أعمى عن خطأٍ وقع. والفرقُ بينهما
 * حرفٌ واحد.
 *
 * وتُبنى على طبقتين، لأنّ الخطأين ليسا سواءً:
 *
 *  ١) **الهيكل** (`quranSkeleton`) — الحروفُ وحدها بلا حركة. به تُعرف **الكلمة**:
 *     أقالها أم أسقطها أم أبدلها بغيرها. وهو الحكمُ الأوثق.
 *
 *  ٢) **المنطوق** (`quranVoweled`) — الحروفُ وحركاتُها، بلا علامات الوقف ولا رموز
 *     التجويد. به تُعرف **الحركة**: أضمّ موضعَ فتح؟ وهو حكمٌ أدقُّ وأضعفُ ثقةً،
 *     ومراجعاتٌ علميّةٌ منشورةٌ تقول إنّ الأنظمة القائمة تُخطئ فيه كثيرًا — فلا يُقال
 *     بثقةِ الأوّل.
 *
 * وحدٌّ لا يُتجاوز: **التسويةُ لا تُقارِن روايةً برواية**. كلُّ قارئٍ يُقابَل بنصّ
 * روايته هو. وإنّما يوحَّد الرسمُ لأنّ ما يُسمع من محرّكٍ صوتيٍّ يُكتب بهجاءٍ آخر —
 * لا ليُقاس ورشٌ بمسطرة حفص.
 */

/* علاماتٌ لا تُنطق: وقفٌ، وسجدةٌ، وأرقامُ آي، ورموزُ تجويدٍ صغيرة، وتطويل. */
const SILENT_MARKS = /[ـۖ-۝۞ۣۢۥۦۨ۩۪-ࣰۭ-ࣿ]/g;

/* حركاتٌ ومدٌّ: تُحذف في الهيكل وتبقى في المنطوق. */
const VOWEL_MARKS = /[ً-ْٖٓ-ٰٟ۟۠ۡۤۧ]/g;

/* صورُ الألف تُوحَّد في الهيكل وحدَه — والمدُّ والهمزُ حركةٌ لا حرفٌ مستقلّ هنا. */
const ALEF_FORMS = /[آأإٱٲٳٵ]/g;

/** ما يُنطق: الحروفُ وحركاتُها، بلا علامةِ وقفٍ ولا رمزِ تجويد. */
export function quranVoweled(text: string): string {
  return String(text || '').normalize('NFC').replace(SILENT_MARKS, '').replace(/\s+/g, ' ').trim();
}

/**
 * هيكلُ الكلمة: حروفُها وحدها.
 *
 * وتُوحَّد صورُ الألف، والألفُ المقصورةُ بالياء، لأنّ محرّكًا صوتيًّا يكتبها كيفما
 * تعلّم. ولا تُوحَّد التاءُ المربوطةُ بالهاء: بينهما فرقٌ يُسمع.
 */
export function quranSkeleton(text: string): string {
  return quranVoweled(text)
    .replace(VOWEL_MARKS, '')
    .replace(ALEF_FORMS, 'ا')
    /*
     * والياءُ المرسومةُ في مصاحف ورشٍ ياءٌ بَرِّيّة (U+06D2)، وفي مصاحف حفصٍ ياءٌ
     * معتادة. قِيس: ٢٩٩٦ موضعًا في ورشٍ وصفرٌ في حفص — كما أنّ ألفَ الوصل (U+0671)
     * ١٣٤٨٣ موضعًا في حفصٍ وصفرٌ في ورش. وهما رسمان لمنطوقٍ واحد؛ ولولا توحيدُهما
     * لقيل «كلمةٌ غيرُ كلمة» في آلاف المواضع الصحيحة.
     */
    .replace(/[ىے]/g, 'ي')
    .replace(/[ٕٔ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/*
 * الألفُ الخنجريّة (U+0670) مدٌّ يُكتب ألفًا في الهجاء الحديث حينًا ويُترك حينًا:
 * «ٱلۡعَٰلَمِينَ» تُكتب «العالمين»، و«ٱلرَّحۡمَٰنِ» تُكتب «الرحمن». فلا قاعدةَ تُطّرد.
 *
 * فيُقبل الاتّفاقُ إذا لم يفترق الرسمان إلا بألف. وثمنُه معلوم: كلمتان لا تختلفان
 * إلا بألفٍ (عالم/علم) تُعدّان واحدة على مستوى الكلمة. وذلك أهونُ من تخطئة قارئٍ
 * مصيبٍ في كلّ موضعِ مدٍّ — ومن اختلف في الحركة يُدركه كشفُ الحركة حين يُؤذن به.
 */
const withoutAlef = (skeleton: string) => skeleton.replace(/\u0627/g, '');

/** أهي الكلمةُ نفسُها حرفًا بحرف — بصرف النظر عن الحركة ورسمِ المدّ؟ */
export function sameWord(a: string, b: string): boolean {
  const sa = quranSkeleton(a), sb = quranSkeleton(b);
  if (!sa.length || !sb.length) return false;
  if (sa === sb) return true;
  const stripped = withoutAlef(sa);
  return stripped.length > 0 && stripped === withoutAlef(sb);
}

/** أهي بحركتها أيضًا؟ يُسأل بعد أن تثبت الكلمة، لا قبله. */
export const sameVowels = (a: string, b: string) => quranVoweled(a) === quranVoweled(b);
